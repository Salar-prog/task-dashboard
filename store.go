// pgDialect selects Postgres ($n) over SQLite (?) placeholders. Set once via
// OpenDB; tests flip it with SetDialectPG around in-memory cases.
var pgDialect bool

func SetDialectPG(pg bool) { pgDialect = pg }

// Q rewrites ? placeholders to $n for Postgres; SQLite passes through.
// String literals are skipped so a '?' inside quotes is never rewritten.
func Q(q string) string {
	if !pgDialect {
		return q
	}
	var b strings.Builder
	n := 0
	inStr := false
	for i := 0; i < len(q); i++ {
		c := q[i]
		if c == '\'' {
			if inStr && i+1 < len(q) && q[i+1] == '\'' {
				b.WriteString("''")
				i++
				continue
			}
			inStr = !inStr
			b.WriteByte(c)
			continue
		}
		if c == '?' && !inStr {
			n++
			fmt.Fprintf(&b, "$%d", n)
			continue
		}
		b.WriteByte(c)
	}
	return b.String()
}

// OpenDB opens sqlite:<path> (or a bare path) and postgres:// DSNs,
// arming the matching placeholder dialect.
func OpenDB(dsn string) (*sql.DB, error) {
	if strings.HasPrefix(dsn, "postgres://") || strings.HasPrefix(dsn, "postgresql://") {
		pgDialect = true
		return sql.Open("pgx", dsn)
	}
	pgDialect = false
	return sql.Open("sqlite", strings.TrimPrefix(dsn, "sqlite:"))
}

// Task is the minimal board row pinned by docs/02-data-model.md.
type Task struct {
	ID           int64
	Title        string
	Desc         string
	Priority     string // low|medium|high|urgent
	Assigner     string
	Owner        string
	RoutineLabel string
	Recurrence   string // none|daily|weekly|monthly
	RelatedTo    string
	Status       string // todo|in_progress|blocked|done
	Progress     int
	Source       string // manual|teams|outlook
	SourceRef    string
	CreatedBy    string
	Deadline     time.Time // zero = none
}

// User is a login identity: local bcrypt password for the board, plus an
// optional sealed mailbox secret for IMAP polling (role gates the board).
type User struct {
	Email           string
	DisplayName     string
	Role            string // member|senior
	PasswordHash    string
	SecretEnc       []byte // sealed app password, empty until /connect
	RefreshTokenEnc []byte // legacy Entra token, unused on local-auth branch
	OutlookFolderID string
	Connected       bool
}

// Migrate creates the tables (idempotent) in the active dialect.
// deadline stays TEXT (RFC3339) on both: all date logic lives in Go,
// which avoids TIMESTAMP scan-shape differences between drivers.
func Migrate(db *sql.DB) error {
	idPK := "id INTEGER PRIMARY KEY AUTOINCREMENT"
	blob := "BLOB"
	if pgDialect {
		idPK = "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
		blob = "BYTEA"
	}
	stmts := []string{
		`CREATE TABLE IF NOT EXISTS tasks(` + idPK + `, title TEXT NOT NULL,
			"desc" TEXT NOT NULL DEFAULT '', priority TEXT NOT NULL DEFAULT 'medium',
			assigner TEXT NOT NULL DEFAULT '', owner TEXT NOT NULL DEFAULT '',
			deadline TEXT, routine_label TEXT NOT NULL DEFAULT '',
			recurrence TEXT NOT NULL DEFAULT 'none', related_to TEXT NOT NULL DEFAULT '',
			status TEXT NOT NULL DEFAULT 'todo', progress_pct INTEGER NOT NULL DEFAULT 0,
			source TEXT NOT NULL DEFAULT 'manual', source_ref TEXT UNIQUE,
			created_by TEXT NOT NULL DEFAULT '',
			created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
			updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
		)`,
		`CREATE INDEX IF NOT EXISTS idx_tasks_source_ref ON tasks(source_ref)`,
		`CREATE TABLE IF NOT EXISTS users(
			email TEXT PRIMARY KEY, display_name TEXT NOT NULL, role TEXT NOT NULL DEFAULT 'senior',
			password_hash TEXT NOT NULL DEFAULT '', secret_enc ` + blob + `,
			refresh_token_enc ` + blob + `, outlook_folder_id TEXT NOT NULL DEFAULT '',
			connected INTEGER NOT NULL DEFAULT 0,
			updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
		)`,
		`CREATE TABLE IF NOT EXISTS task_events(` + idPK + `,
			task_id INTEGER NOT NULL REFERENCES tasks(id),
			actor TEXT NOT NULL, from_status TEXT NOT NULL, to_status TEXT NOT NULL,
			note TEXT NOT NULL DEFAULT '', at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
		)`,
		`CREATE TABLE IF NOT EXISTS import_errors(` + idPK + `, source TEXT NOT NULL,
			ref TEXT NOT NULL DEFAULT '', err TEXT NOT NULL,
			at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
		)`,
	}
	for _, s := range stmts {
		if _, err := db.Exec(s); err != nil {
			return err
		}
	}
	// Upgrade path for pre-local-auth databases missing the new columns.
	for _, col := range []struct{ name, ddl string }{
		{"password_hash", "TEXT NOT NULL DEFAULT ''"},
		{"secret_enc", blob},
	} {
		if err := ensureColumn(db, "users", col.name, col.ddl); err != nil {
			return err
		}
	}
	return nil
}

func ensureColumn(db *sql.DB, table, name, ddl string) error {
	_, err := db.Exec(fmt.Sprintf("ALTER TABLE %s ADD COLUMN %s %s", table, name, ddl))
	if err == nil {
		return nil
	}
	msg := err.Error()
	if strings.Contains(msg, "duplicate column") || strings.Contains(msg, "already exists") {
		return nil // SQLite: duplicate column name; Postgres: 42701 already exists
	}
	return err
}

func nullableTime(t time.Time) any {
	if t.IsZero() {
		return nil
	}
	return t.UTC().Format(time.RFC3339)
}

// ImportTask inserts an Outlook task, or returns the existing id on source_ref.
// inserted=false on re-poll duplicates.
// ponytail: ON CONFLICT DO NOTHING (valid SQLite + Postgres) keeps re-polls
// a no-op without a read-modify-write race; RETURNING separates insert/skip.
func ImportTask(db *sql.DB, source, ref, title, assigner, owner, actor string) (id int64, inserted bool, err error) {
	err = db.QueryRow(Q(
		`INSERT INTO tasks(title, assigner, owner, source, source_ref, created_by)
		 VALUES(?,?,?,?,?,?) ON CONFLICT(source_ref) DO NOTHING RETURNING id`,
	), title, assigner, owner, source, ref, actor).Scan(&id)
	if err == sql.ErrNoRows {
		if err := db.QueryRow(Q(`SELECT id FROM tasks WHERE source_ref=?`), ref).Scan(&id); err != nil {
			return 0, false, err
		}
		return id, false, nil
	}
	if err != nil {
		return 0, false, err
	}
	if _, err := db.Exec(Q(
		`INSERT INTO task_events(task_id, actor, from_status, to_status, note) VALUES(?, ?, '', 'todo', 'auto-import')`,
	), id, actor); err != nil {
		return 0, false, err
	}
	return id, true, nil
}

// CreateTask inserts a manual/board task with sane defaults.
func CreateTask(db *sql.DB, task Task) (int64, error) {
	if task.Priority == "" {
		task.Priority = "medium"
	}
	if task.Status == "" {
		task.Status = "todo"
	}
	if task.Recurrence == "" {
		task.Recurrence = "none"
	}
	var id int64
	err := db.QueryRow(Q(
		`INSERT INTO tasks(title, "desc", priority, assigner, owner, deadline, routine_label,
		 recurrence, related_to, status, progress_pct, source, created_by)
		 VALUES(?,?,?,?,?,?,?,?,?,?,?, 'manual', ?) RETURNING id`,
	),
		task.Title, task.Desc, task.Priority, task.Assigner, task.Owner,
		nullableTime(task.Deadline), task.RoutineLabel, task.Recurrence, task.RelatedTo,
		task.Status, task.Progress, task.CreatedBy).Scan(&id)
	if err != nil {
		return 0, err
	}
	if _, err := db.Exec(Q(
		`INSERT INTO task_events(task_id, actor, from_status, to_status, note) VALUES(?, '', '', ?, 'create')`,
	), id, task.Status); err != nil {
		return 0, err
	}
	return id, nil
}

// UpsertUser inserts or refreshes identity/role on each login.
func UpsertUser(db *sql.DB, u User) error {
	_, err := db.Exec(Q(
		`INSERT INTO users(email, display_name, role) VALUES(?,?,?)
		 ON CONFLICT(email) DO UPDATE SET display_name=excluded.display_name, role=excluded.role,
		 updated_at=CURRENT_TIMESTAMP`,
	), u.Email, u.DisplayName, u.Role)
	return err
}

// GetUser returns sql.ErrNoRows for unknown emails.
func GetUser(db *sql.DB, email string) (User, error) {
	var u User
	var connected int
	var secret, refresh sql.NullString
	err := db.QueryRow(Q(
		`SELECT email, display_name, role, password_hash, secret_enc, refresh_token_enc,
		 COALESCE(outlook_folder_id,''), connected FROM users WHERE email=?`,
	), email).
		Scan(&u.Email, &u.DisplayName, &u.Role, &u.PasswordHash, &secret, &refresh,
			&u.OutlookFolderID, &connected)
	if err != nil {
		return User{}, err
	}
	u.SecretEnc = []byte(secret.String)
	u.RefreshTokenEnc = []byte(refresh.String)
	u.Connected = connected == 1
	return u, nil
}

// SetUserConnected caches the sealed secret + folder after /connect.
func SetUserConnected(db *sql.DB, email string, sealedToken []byte, folderID string) error {
	_, err := db.Exec(Q(
		`UPDATE users SET secret_enc=?, outlook_folder_id=?, connected=1, updated_at=CURRENT_TIMESTAMP
		 WHERE email=?`,
	), sealedToken, folderID, email)
	return err
}

func SetUserToken(db *sql.DB, email string, sealed []byte) error {
	_, err := db.Exec(Q(`UPDATE users SET refresh_token_enc=?, updated_at=CURRENT_TIMESTAMP WHERE email=?`), sealed, email)
	return err
}

func ClearUserToken(db *sql.DB, email string) error {
	_, err := db.Exec(Q(`UPDATE users SET refresh_token_enc=NULL, secret_enc=NULL, connected=0, updated_at=CURRENT_TIMESTAMP WHERE email=?`), email)
	return err
}

// OpenUserSecret decrypts a member's stored mailbox secret. Empty means
// never connected (/connect not done) and is an error, not a blank login.
func OpenUserSecret(db *sql.DB, key []byte, email string) ([]byte, error) {
	u, err := GetUser(db, email)
	if err != nil {
		return nil, err
	}
	if len(u.SecretEnc) == 0 {
		return nil, fmt.Errorf("user %s has no mail secret", email)
	}
	return OpenToken(key, u.SecretEnc)
}

func SetUserPassword(db *sql.DB, email, hash string) error {
	_, err := db.Exec(Q(`UPDATE users SET password_hash=?, updated_at=CURRENT_TIMESTAMP WHERE email=?`), hash, email)
	return err
}

// SeedUsers creates missing accounts from "email:role,..." with a default
// password. Existing users are never touched (no password resets on restart).
func SeedUsers(db *sql.DB, spec, password string) error {
	if strings.TrimSpace(spec) == "" {
		return nil
	}
	hash, err := bcrypt.GenerateFromPassword([]byte(password), bcrypt.DefaultCost)
	if err != nil {
		return err
	}
	for _, pair := range strings.Split(spec, ",") {
		pair = strings.TrimSpace(pair)
		if pair == "" {
			continue
		}
		email, role, ok := strings.Cut(pair, ":")
		if !ok || !strings.Contains(email, "@") || (role != "member" && role != "senior") {
			return fmt.Errorf("bad seed entry %q", pair)
		}
		if _, err := GetUser(db, email); err == nil {
			continue
		}
		if err := UpsertUser(db, User{Email: email, DisplayName: email, Role: role}); err != nil {
			return err
		}
		if err := SetUserPassword(db, email, string(hash)); err != nil {
			return err
		}
	}
	return nil
}

var recurrenceSteps = map[string]time.Duration{
	"daily":   24 * time.Hour,
	"weekly":  7 * 24 * time.Hour,
	"monthly": 30 * 24 * time.Hour,
}

// GetTask returns sql.ErrNoRows for unknown ids.
func GetTask(db *sql.DB, id int64) (Task, error) {
	var t Task
	var deadline sql.NullString
	err := db.QueryRow(Q(
		`SELECT id, title, "desc", priority, assigner, owner, deadline, routine_label,
		 recurrence, related_to, status, progress_pct, source, COALESCE(source_ref,''), created_by
		 FROM tasks WHERE id=?`,
	), id).
		Scan(&t.ID, &t.Title, &t.Desc, &t.Priority, &t.Assigner, &t.Owner, &deadline,
			&t.RoutineLabel, &t.Recurrence, &t.RelatedTo, &t.Status, &t.Progress,
			&t.Source, &t.SourceRef, &t.CreatedBy)
	if err != nil {
		return Task{}, err
	}
	if deadline.Valid && deadline.String != "" {
		if d, err := time.Parse(time.RFC3339, deadline.String); err == nil {
			t.Deadline = d
		}
	}
	return t, nil
}

// UpdateTask writes the full row (callers overlay onto GetTask first).
func UpdateTask(db *sql.DB, t Task) error {
	res, err := db.Exec(Q(
		`UPDATE tasks SET title=?, "desc"=?, priority=?, assigner=?, owner=?, deadline=?,
		 routine_label=?, recurrence=?, related_to=?, updated_at=CURRENT_TIMESTAMP WHERE id=?`,
	),
		t.Title, t.Desc, t.Priority, t.Assigner, t.Owner, nullableTime(t.Deadline),
		t.RoutineLabel, t.Recurrence, t.RelatedTo, t.ID)
	if err != nil {
		return err
	}
	if n, _ := res.RowsAffected(); n == 0 {
		return sql.ErrNoRows
	}
	return nil
}

// ListTasks returns tasks honoring owner/status/priority/q filters (empty = all).
func ListTasks(db *sql.DB, owner, status, priority, q string) ([]Task, error) {
	query := `SELECT id, title, "desc", priority, assigner, owner, deadline, routine_label,
	 recurrence, related_to, status, progress_pct, source, COALESCE(source_ref,''), created_by
	 FROM tasks WHERE 1=1`
	var args []any
	if owner != "" {
		query += ` AND owner=?`
		args = append(args, owner)
	}
	if status != "" {
		query += ` AND status=?`
		args = append(args, status)
	}
	if priority != "" {
		query += ` AND priority=?`
		args = append(args, priority)
	}
	if q != "" {
		query += ` AND (title LIKE ? OR "desc" LIKE ? OR related_to LIKE ?)`
		like := "%" + q + "%"
		args = append(args, like, like, like)
	}
	query += ` ORDER BY id`
	rows, err := db.Query(Q(query), args...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []Task
	for rows.Next() {
		var t Task
		var deadline sql.NullString
		if err := rows.Scan(&t.ID, &t.Title, &t.Desc, &t.Priority, &t.Assigner, &t.Owner,
			&deadline, &t.RoutineLabel, &t.Recurrence, &t.RelatedTo, &t.Status, &t.Progress,
			&t.Source, &t.SourceRef, &t.CreatedBy); err != nil {
			return nil, err
		}
		if deadline.Valid && deadline.String != "" {
			if d, err := time.Parse(time.RFC3339, deadline.String); err == nil {
				t.Deadline = d
			}
		}
		out = append(out, t)
	}
	return out, rows.Err()
}

var validStatuses = map[string]bool{"todo": true, "in_progress": true, "blocked": true, "done": true}

// UpdateProgress moves status + % together, logs history, and clones on done
// for recurring tasks (clone id returned via UpdateProgressDone).
func UpdateProgress(db *sql.DB, id int64, status string, pct int, note, actor string) error {
	_, err := updateProgress(db, id, status, pct, note, actor)
	return err
}

// UpdateProgressDone closes a task; returns the recurrence clone id (0 when none).
func UpdateProgressDone(db *sql.DB, id int64, actor string) (int64, error) {
	return updateProgress(db, id, "done", 100, "", actor)
}

func updateProgress(db *sql.DB, id int64, status string, pct int, note, actor string) (int64, error) {
	if !validStatuses[status] {
		return 0, fmt.Errorf("unknown status %q", status)
	}
	if pct < 0 || pct > 100 {
		return 0, fmt.Errorf("progress %d out of range", pct)
	}
	if status == "blocked" && note == "" {
		return 0, fmt.Errorf("blocked requires a reason note")
	}
	tx, err := db.Begin()
	if err != nil {
		return 0, err
	}
	defer tx.Rollback()

	var recurrence, from string
	if err := tx.QueryRow(Q(`SELECT recurrence, status FROM tasks WHERE id=?`), id).
		Scan(&recurrence, &from); err != nil {
		return 0, fmt.Errorf("task %d: %w", id, err)
	}
	now := time.Now().UTC().Format(time.RFC3339)
	if _, err := tx.Exec(Q(`UPDATE tasks SET status=?, progress_pct=?, updated_at=? WHERE id=?`),
		status, pct, now, id); err != nil {
		return 0, err
	}
	if _, err := tx.Exec(Q(
		`INSERT INTO task_events(task_id, actor, from_status, to_status, note) VALUES(?,?,?,?,?)`,
	), id, actor, from, status, note); err != nil {
		return 0, err
	}
	if status != "done" {
		return 0, tx.Commit()
	}
	step, ok := recurrenceSteps[recurrence]
	if !ok {
		return 0, tx.Commit() // none or unknown: no clone
	}
	cloneID, err := cloneNext(tx, id, actor, time.Now().UTC().Add(step))
	if err != nil {
		return 0, err
	}
	return cloneID, tx.Commit()
}

// CompleteTask marks done and clones the next occurrence for recurring tasks.
// Returns 0 with no error when recurrence is none.
func CompleteTask(db *sql.DB, id int64, actor string) (int64, error) {
	return UpdateProgressDone(db, id, actor)
}

func cloneNext(tx *sql.Tx, id int64, actor string, next time.Time) (int64, error) {
	var cloneID int64
	if err := tx.QueryRow(Q(
		`INSERT INTO tasks(title, "desc", priority, assigner, owner, deadline, routine_label,
			recurrence, related_to, status, progress_pct, source, created_by)
		 SELECT title, "desc", priority, assigner, owner, ?, routine_label,
			recurrence, related_to, 'todo', 0, source, ?
		 FROM tasks WHERE id=? RETURNING id`,
	), next.Format(time.RFC3339), actor, id).Scan(&cloneID); err != nil {
		return 0, err
	}
	if _, err := tx.Exec(Q(
		`INSERT INTO task_events(task_id, actor, from_status, to_status, note) VALUES(?, ?, '', 'todo', ?)`,
	), cloneID, actor, fmt.Sprintf("recurrence clone of #%d", id)); err != nil {
		return 0, err
	}
	return cloneID, nil
}

func LogImportError(db *sql.DB, source, ref string, ierr error) error {
	_, err := db.Exec(Q(`INSERT INTO import_errors(source, ref, err) VALUES(?,?,?)`), source, ref, ierr.Error())
	return err
}

type Event struct {
	Actor, From, To, Note string
}

func ListEvents(db *sql.DB, taskID int64, limit int) ([]Event, error) {
	rows, err := db.Query(Q(`SELECT actor, from_status, to_status, note FROM task_events WHERE task_id=? ORDER BY id DESC LIMIT ?`), taskID, limit)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []Event
	for rows.Next() {
		var e Event
		if err := rows.Scan(&e.Actor, &e.From, &e.To, &e.Note); err != nil {
			return nil, err
		}
		out = append(out, e)
	}
	return out, rows.Err()
}

